-- Отложенный вызов без внешних библиотек (уникальное имя контекстного таймера на каждый вызов)
RPG._after_id = RPG._after_id or 0
function RPG.After(delay, fn)
	RPG._after_id = RPG._after_id + 1
	local name = "rpg_after_" .. RPG._after_id
	GameRules:GetGameModeEntity():SetContextThink(name, function()
		fn()
		return nil
	end, delay)
end

